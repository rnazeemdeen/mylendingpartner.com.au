<h2>Eligibility caps apply</h2>
<p>This is the part most summaries leave out, so it's worth stating plainly. Help to Buy has income caps, property price caps that vary by location, and a limited number of places. Meeting the deposit requirement is not the same as being eligible.</p>
<p>The caps are indexed and reviewed periodically. We'll check the current position against your circumstances rather than guessing.</p>

<h2>The trade-off worth understanding</h2>
<p>Shared equity means shared capital growth. If the property rises in value, the government's share rises with it, and you'll typically repay their contribution based on the value at the time you buy them out or sell &ndash; not the amount originally contributed.</p>
<p>That isn't a hidden catch; it's the basis of the arrangement. But it means the scheme is not simply "free deposit help," and the long-term arithmetic is different from an ordinary purchase. It's worth modelling both before deciding.</p>
<p>You can generally buy out the government's share over time, subject to the scheme rules.</p>

