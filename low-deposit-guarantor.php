<h2>Government guarantee schemes</h2>
<p>Eligible buyers may be able to purchase with a low deposit and without paying LMI, because the government guarantees part of the loan. Eligibility rules and property price caps apply and change periodically. <a href="schemes">See the current schemes</a>.</p>

<h2>Family guarantor arrangements</h2>
<p>A family member &ndash; usually a parent &ndash; offers equity in their own property as additional security for part of your loan. This can let you buy sooner and avoid LMI without anyone handing over cash.</p>
<p><b>This is a serious commitment and it should be treated as one.</b> If the loan isn't repaid, the guarantor's own property is at risk. The guarantee also affects their borrowing capacity while it's in place, which matters if they have plans of their own.</p>
<p>Well-structured guarantees limit the guarantor's exposure to a defined portion of the loan rather than the whole thing, and include a clear path to releasing the guarantee once enough equity has built up. I'll walk your family through exactly what they'd be agreeing to, in whichever language suits them &ndash; and I'd encourage any guarantor to get independent legal advice before signing.</p>

<h2>Low-deposit lending and LMI</h2>
<p>Outside the schemes, many lenders will lend above 80% of the property value with LMI. The premium varies with the loan size and the deposit percentage, and it can sometimes be added to the loan rather than paid upfront.</p>
<p>Lenders also differ in appetite here. Some are comfortable at higher loan-to-value ratios; others aren't. Knowing which is which saves wasted applications.</p>

<h2>The honest question</h2>
<p>Buying with a small deposit means a larger loan, higher repayments, and less buffer if values fall or rates rise. That may still be the right decision &ndash; waiting has costs too. But it should be a decision made with both sides visible, and that's the conversation I'd rather have with you than a sales pitch.</p>

