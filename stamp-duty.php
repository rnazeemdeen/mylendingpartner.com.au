<h2>Why this matters more than the grant</h2>
<p>For many first home buyers, a stamp duty exemption is worth considerably more than the first home owner grant &ndash; and unlike the grant, it usually applies to established homes as well as new ones.</p>
<p>It also directly reduces the cash you need at settlement, which can be the difference between buying this year and next.</p>

<h2>How it interacts with your loan</h2>
<p>Duty is generally payable at settlement and can't be added to your loan. If you're eligible for an exemption, the funds you need to complete drop accordingly, which affects how much deposit you need and sometimes which schemes you can use.</p>
<p>Getting this right early changes your whole budget, so it's one of the first things I check.</p>

