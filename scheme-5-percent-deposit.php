<p class="lede">The Australian Government 5% Deposit Scheme helps eligible first home buyers purchase a home with a lower deposit and avoid Lenders Mortgage Insurance. The government guarantees part of the loan, which is what allows the lender to accept a smaller deposit without insurance.</p>

<h2>Key features</h2>
<ul>
  <li>From a 5% deposit for eligible first home buyers</li>
  <li>No LMI payable under the scheme</li>
  <li>Available for both new and existing homes</li>
  <li>Property price caps apply, and they vary by location</li>
  <li>Under the expanded scheme, income caps have been removed and places are not limited</li>
</ul>
<p>There is also a 2% deposit pathway available to eligible single parents.</p>

<h2>Who it tends to suit</h2>
<p>First home buyers with a strong, stable income who haven't yet accumulated a 20% deposit. If your capacity to <em>repay</em> is well ahead of your capacity to <em>save</em> &ndash; which is a very common position, particularly while renting &ndash; this is the scheme most likely to be relevant.</p>

<h2>What to think about before using it</h2>
<p>Buying with a 5% deposit means borrowing 95% of the value. Your repayments will be higher than they would be with a larger deposit, and you'll have less buffer if property values soften. Avoiding LMI is a genuine saving, but it doesn't change the size of the loan.</p>
<p>The property price caps also shape where and what you can buy, and they may not stretch as far as you'd like in some markets. Worth checking before you fall in love with something.</p>

<div class="note">Eligibility is determined by the Australian Government, not by us or by any lender. Criteria and price caps change from time to time &ndash; we'll confirm what currently applies to your situation and your location.</div>

