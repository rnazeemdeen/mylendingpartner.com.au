<h2>When refinancing isn't worth it</h2>
<p>Worth saying plainly, because it comes up often:</p>
<ul>
  <li><b>You're in a fixed term.</b> Break costs can wipe out the benefit entirely.</li>
  <li><b>Your equity position is thin.</b> If you'd trigger LMI again, the sums often don't work.</li>
  <li><b>Your circumstances have changed recently.</b> A new business, a career break or reduced income can mean a new lender assesses you less favourably than your current one already has.</li>
  <li><b>The saving is marginal.</b> Switching costs time and paperwork. A tiny rate difference may not justify it.</li>
</ul>
<p>Sometimes the better move is asking your current lender to reprice. That costs nothing and occasionally works. I'll tell you when that's the sensible first step.</p>

<h2>A note on debt consolidation</h2>
<p>Rolling credit cards or personal loans into a mortgage lowers the interest rate on that debt, which looks like an obvious win. The catch is the term: stretching a five-year debt across twenty-five years can mean paying more in total interest despite the lower rate.</p>
<p>It can still be the right call, particularly where cash flow is the immediate problem. But it should be a decision made with the full numbers visible, and ideally alongside a plan to pay the consolidated portion down faster.</p>

