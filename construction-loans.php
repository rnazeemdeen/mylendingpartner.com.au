<h2>How progress payments work</h2>
<p>Funds are typically released across defined stages &ndash; commonly slab, frame, lock-up, fit-out and completion. The lender usually requires an inspection or valuation before releasing each drawdown.</p>
<p>Two practical consequences. First, your repayments increase as more of the loan is drawn, so your costs ramp through the build rather than starting at full rate. Second, if you're renting while you build, you're carrying both rent and a growing loan repayment at the same time. That overlap is the part people underestimate.</p>

<h2>Why the building contract matters to your lender</h2>
<p>Lenders scrutinise building contracts closely. A fixed-price contract from a licensed builder is the most straightforward path. Cost-plus arrangements, owner-builder projects and unusual construction methods all narrow the field of lenders willing to participate.</p>
<p>It's worth having the finance conversation <em>before</em> signing with a builder, not after. Changing builders because your lender won't accept the contract is a painful and avoidable problem.</p>

<h2>Grants and building</h2>
<p>Building is often where first home owner grants actually apply, since many state grants are limited to new homes and house-and-land packages rather than established properties. If you're building your first home, check <a href="schemes">what's available in your state</a>.</p>

