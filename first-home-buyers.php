<h2>The deposit question</h2>
<p>The standard answer is 20% of the purchase price. The real answer is that plenty of first home buyers purchase with far less, using a combination of government schemes, family security, or by paying Lenders Mortgage Insurance.</p>
<p>Which of those makes sense depends on how long saving a larger deposit would take, what the market is doing in the meantime, and your appetite for the trade-offs involved.</p>

<h2>Lenders Mortgage Insurance</h2>
<p>LMI is commonly misunderstood as a penalty. It isn't &ndash; it's an insurance premium that protects the lender, not you, and it's what allows lenders to say yes at a higher loan-to-value ratio.</p>
<p>The useful question is not "how do I avoid LMI" but "what does LMI cost me, and is that less than the cost of waiting?" Sometimes paying it is clearly right. Sometimes it clearly isn't. It depends on the numbers, and we can run them.</p>
<p>There are also ways to avoid it entirely &ndash; government guarantee schemes, a family guarantor, or certain professional exemptions. See <a href="schemes">government schemes</a> and <a href="low-deposit-guarantor">low deposit and guarantor loans</a>.</p>

<h2>Government help</h2>
<p>Depending on your circumstances and your state, you may be eligible for a low-deposit guarantee scheme, a shared-equity arrangement, a first home owner grant, a stamp duty exemption or concession, or some combination.</p>
<p>These have different eligibility rules, different price caps, and they change regularly. I keep across them so you don't have to. <a href="schemes">See the current schemes</a>.</p>

<h2>Pre-approval</h2>
<p>Pre-approval tells you your number and tells an agent you're a real buyer rather than a hopeful one. It's worth having before you start seriously looking.</p>
<p>It also has limits that plenty of buyers misunderstand &ndash; it isn't unconditional, it's usually subject to valuation and to your circumstances not changing, and it expires. Worth understanding exactly what yours covers before you bid.</p>

