    <p class="lede">Almost everyone arrives at this decision the same way: they've heard a rate somewhere and want to know if it's good. That's the wrong starting question. The rate matters, but so do the features you'll actually use, the flexibility you'll want in three years, and whether your budget can absorb a rise without stress.</p>
<p>Here's how the three structures differ, and who each tends to suit.</p>
    
<h2>Variable rate</h2>
<p>Your interest rate moves up or down with market conditions. Repayments change accordingly.</p>
<p><b>May suit</b> borrowers who want flexibility, the ability to make additional repayments without penalty, and features such as an offset account or redraw.</p>
<p>The trade-off is uncertainty. If rates rise, your repayment rises, and a budget with no headroom feels that quickly.</p>

<h2>Fixed rate</h2>
<p>Your rate is locked for an agreed period, commonly one to five years. Repayments stay the same for that term regardless of what the market does.</p>
<p><b>May suit</b> borrowers who want certainty around repayments &ndash; often those on a tight budget, or planning around a single income for a period.</p>
<p>The trade-offs are real and worth understanding before you commit: fixed loans usually restrict extra repayments, rarely offer a full offset account, and can carry significant break costs if you need to exit early. Selling the property or refinancing during a fixed term can be expensive.</p>

<h2>Split loan</h2>
<p>Part of the loan is fixed, part is variable.</p>
<p><b>May suit</b> borrowers who want some repayment certainty while keeping flexibility and offset benefits on the remainder.</p>
<p>A split isn't a hedge that guarantees you win either way &ndash; it guarantees you're partly right and partly wrong. That's precisely the point. It reduces the consequence of the decision, which for many people is worth more than optimising it.</p>

<h2>How I approach the choice</h2>
<p>I'll ask what your budget looks like with a two percentage point rise, whether you're likely to sell or refinance inside three years, and whether you'll realistically use an offset. Those three answers usually settle it faster than any rate comparison.</p>

