<h2>How much is available</h2>
<p>Lenders typically allow borrowing up to a percentage of the property's value, less what you currently owe. Going beyond a certain loan-to-value ratio generally triggers LMI, which changes the arithmetic.</p>
<p>Lenders also ask what the funds are for, and some purposes are scrutinised more closely than others. Larger cash-out amounts usually require evidence of purpose.</p>

<h2>The part worth pausing on</h2>
<p>Equity release converts something you own into something you owe. Used to buy an appreciating asset or to improve the property itself, that can be sound. Used to fund consumption, it turns a short-term expense into a debt secured against the roof over your head, repaid across decades.</p>
<p>The interest rate is attractive precisely <em>because</em> your home is the security. That's the trade-off, and it's worth naming clearly rather than glossing over.</p>
<p>I'd rather talk you through the downside properly and have you proceed with your eyes open than have you find out later.</p>

