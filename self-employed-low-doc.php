<h2>Why lenders differ so much here</h2>
<p>Two lenders can look at the same tax returns and arrive at very different borrowing capacities. Some add back depreciation; others don't. Some consider retained company profits; many won't. Some require two years of returns; others accept one. Some treat a recent increase in income as real; others average it down.</p>
<p>None of that is visible from the outside, and it's the single biggest reason self-employed borrowers get a disappointing answer from the first lender they try and assume it's the market's answer. It usually isn't.</p>

<h2>Where the accounting background helps</h2>
<p>Reading a set of financials properly &ndash; understanding what sits behind the taxable income figure, what's genuinely a one-off, and how the structure distributes profit &ndash; means I can work out what your position actually supports before we approach anyone.</p>
<p>It also means I can have a sensible conversation with your accountant rather than just forwarding documents.</p>

<h2>Alternative documentation</h2>
<p>Some lenders offer alternative documentation options for borrowers whose circumstances don't suit full financials &ndash; for instance where the most recent year's returns aren't yet available but the business is trading strongly.</p>
<p>These generally come with different rates and conditions than a standard loan. They're a legitimate tool in the right circumstances and an expensive shortcut in the wrong ones.</p>

