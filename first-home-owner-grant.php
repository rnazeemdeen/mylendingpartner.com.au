<p class="lede">The First Home Owner Grant (FHOG) is a one-off payment to eligible first home buyers. Unlike the national deposit schemes, it's run separately by each state and territory &ndash; which means there is no single national answer to "how much do I get."</p>

<h2>What it generally applies to</h2>
<p>In most jurisdictions the grant is aimed at:</p>
<ul>
  <li>Newly built homes</li>
  <li>House-and-land packages</li>
  <li>Substantially renovated properties, in some states</li>
  <li>Owner-builder situations</li>
</ul>
<p>Established homes are usually excluded. This surprises a lot of first home buyers, and it's the most common misunderstanding I encounter &ndash; people budget for a grant they won't receive because they're buying an existing house.</p>

<h2>Why the rules vary so much</h2>
<p>Each state sets its own grant amount, its own property value cap, and its own definition of what qualifies as a new home. Some states have discontinued their grant entirely in favour of stamp duty relief. Others have raised caps recently.</p>
<p>Because these are set at state budgets, they change regularly. Rather than publish figures here that may be out of date by the time you read them, we check the current position with the relevant state revenue office for your purchase.</p>

