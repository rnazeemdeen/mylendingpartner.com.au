<h2>Cross-collateralisation: the thing to get right early</h2>
<p>When lenders secure multiple properties against each other, it feels efficient and often is, in the short term. The problem appears later: selling one property, refinancing, or releasing equity becomes tangled, because every decision touches every property.</p>
<p>Keeping securities separate &ndash; sometimes across different lenders &ndash; costs a little more effort up front and preserves a great deal of flexibility. Whether it's right for you depends on your plans, but it should be a deliberate decision rather than something that happens by default.</p>

<h2>Interest only</h2>
<p>Interest-only periods improve short-term cash flow and can have tax implications worth discussing with your accountant. They also mean you aren't reducing the debt, and repayments step up noticeably when the interest-only period ends.</p>
<p>Lenders assess interest-only applications differently and often price them higher. It's a legitimate tool used deliberately, and a problem when used to make an unaffordable purchase look affordable.</p>

<h2>Where my background helps</h2>
<p>Investment applications live or die on how income is presented &ndash; rental income treatment, negative gearing, existing commitments, and how each lender applies its serviceability assessment. Lenders differ substantially here, and knowing which ones treat your situation favourably is most of the work.</p>
<div class="note">I'm not a tax adviser and can't give tax advice. Investment structure has tax consequences that should be discussed with your accountant &ndash; ideally before you buy, not at tax time.</div>

